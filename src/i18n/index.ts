/** Look up `key` in `lang`'s catalog, falling back to English and then to the
 *  raw key. `{name}` placeholders are filled from `vars`. */
export function t(key: string, lang: string, vars?: Record<string, string>): string {
  let text = (i18n[lang] || i18n["en"])[key] || (i18n["en"][key]) || key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, v);
    });
  }
  return text;
}
